package top.mcfpp.doc

import com.alibaba.fastjson2.JSON
import com.alibaba.fastjson2.JSONWriter
import java.nio.file.Files
import java.nio.file.Path
import top.mcfpp.project.atomicWrite

internal object DocumentationWriter {
    fun write(model: DocumentationModel, directory: Path, format: DocumentationFormat): DocumentationExportResult {
        val destination = directory.toAbsolutePath().normalize()
        val content = linkedMapOf<String, ByteArray>()
        if (format != DocumentationFormat.json) content["index.html"] = html(model).toByteArray(Charsets.UTF_8)
        if (format != DocumentationFormat.html) content["docs.json"] = JSON.toJSONBytes(model, JSONWriter.Feature.PrettyFormat)
        val managed = listOf("index.html", "docs.json").map(destination::resolve)
        val previous = managed.associateWith { if (Files.exists(it)) Files.readAllBytes(it) else null }
        try {
            content.forEach { (name, bytes) -> atomicWrite(destination.resolve(name), bytes) }
            managed.filter { it.fileName.toString() !in content }.forEach { Files.deleteIfExists(it) }
        } catch (failure: Exception) {
            previous.forEach { (path, bytes) ->
                runCatching { if (bytes == null) Files.deleteIfExists(path) else atomicWrite(path, bytes) }.exceptionOrNull()?.let(failure::addSuppressed)
            }
            throw failure
        }
        return DocumentationExportResult(destination, frozen(content.keys.map(destination::resolve)))
    }

    private fun escape(value: String): String = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;").replace("'", "&#39;")

    private fun html(model: DocumentationModel): String = buildString {
        append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">")
        append("<title>${escape(model.title)} · MCFPP API</title><style>").append(style).append("</style></head><body>")
        append("<aside><a class=\"brand\" href=\"#\">MCFPP<span>API DOCUMENTATION</span></a><h1>${escape(model.title)}</h1>")
        append("<label for=\"search\">Search declarations</label><input id=\"search\" type=\"search\" placeholder=\"Name, type, or signature…\" autocomplete=\"off\">")
        append("<nav aria-label=\"Namespaces\"><button data-namespace=\"\" class=\"active\">All namespaces</button>")
        model.symbols.map { it.namespace }.distinct().forEach { namespace -> append("<button data-namespace=\"${escape(namespace)}\">${escape(namespace)}</button>") }
        append("</nav><footer>Generated by MCFPP<br>Available offline</footer></aside><main><header><div class=\"eyebrow\">REFERENCE</div>")
        append("<h2>Explore the API</h2><p><span id=\"count\">${model.symbols.size}</span> declarations · <span id=\"current-namespace\">All namespaces</span></p></header>")
        val included = model.symbols.map { it.id }.toSet()
        for (symbol in model.symbols) {
            val qualified = "${symbol.namespace}:${symbol.owner?.let { "$it." }.orEmpty()}${symbol.name}"
            append("<article id=\"${symbol.id}\" data-namespace=\"${escape(symbol.namespace)}\" data-search=\"${escape("$qualified ${symbol.signature} ${symbol.packageId}".lowercase())}\">")
            append("<div class=\"meta\"><span class=\"kind\">${escape(symbol.kind)}</span><span>${escape(symbol.access)}</span><span>${escape(symbol.packageId)}</span></div>")
            append("<h3><a class=\"permalink\" href=\"#${symbol.id}\">${escape(qualified)}</a></h3><pre class=\"signature\"><code>${escape(symbol.signature)}</code></pre>")
            symbol.inheritedFrom?.let { origin ->
                append("<p class=\"source\">Inherited from ")
                if (origin in included) append("<a href=\"#$origin\">original declaration</a>") else append("original declaration")
                append("</p>")
            }
            for (tag in symbol.tags.filter { it.name == "deprecated" }) append("<div class=\"deprecated\"><strong>Deprecated</strong>${DocumentationMarkdown.html(tag.content, symbol)}</div>")
            append("<div class=\"markdown\">${DocumentationMarkdown.html(symbol.markdown, symbol)}</div>")
            if (symbol.readonlyParameters.isNotEmpty() || symbol.parameters.isNotEmpty()) {
                append("<h4>Parameters</h4><dl>")
                (symbol.readonlyParameters + symbol.parameters).forEach { parameter ->
                    append("<dt><code>${escape(parameter.name)}</code><span>${escape(parameter.type)}</span>")
                    parameter.defaultValue?.let { append("<span> = ${escape(it)}</span>") }
                    append("</dt><dd>")
                    symbol.tags.filter { it.name == "param" && it.subject == parameter.name }.forEach { append(DocumentationMarkdown.html(it.content, symbol)) }
                    append("</dd>")
                }
                append("</dl>")
            }
            for (tag in symbol.tags.filter { it.name !in setOf("param", "deprecated") }) {
                append("<div class=\"tag\"><h4>${escape(tag.name.replaceFirstChar { it.uppercase() })}${tag.subject?.let { " · ${escape(it)}" }.orEmpty()}</h4>")
                val target = if (tag.name == "see") DocumentationMarkdown.seeTarget(tag.content) else null
                val reference = symbol.references.firstOrNull { it.text == target && it.included }
                if (reference != null) {
                    append("<p><a href=\"#${reference.target}\">${escape(target!!)}</a>${escape(tag.content.removePrefix(target))}</p>")
                } else append(DocumentationMarkdown.html(tag.content, symbol))
                append("</div>")
            }
            symbol.source?.let { append("<div class=\"source\">${escape(it.file)}:${it.line}</div>") }
            append("</article>")
        }
        append("<p id=\"empty\" hidden>No declarations match your search.</p></main><script>").append(script).append("</script></body></html>")
    }

    private val script = """
        const search = document.getElementById('search');
        const articles = Array.from(document.querySelectorAll('article'));
        const buttons = Array.from(document.querySelectorAll('nav button'));
        let namespace = '';
        function filter() {
          const query = search.value.trim().toLowerCase(); let count = 0;
          for (const article of articles) {
            article.hidden = (namespace && article.dataset.namespace !== namespace) || !article.dataset.search.includes(query);
            if (!article.hidden) count++;
          }
          document.getElementById('count').textContent = count;
          document.getElementById('empty').hidden = count !== 0;
          document.getElementById('current-namespace').textContent = namespace || 'All namespaces';
          buttons.forEach(button => button.classList.toggle('active', button.dataset.namespace === namespace));
        }
        search.addEventListener('input', filter);
        buttons.forEach(button => button.addEventListener('click', () => { namespace = button.dataset.namespace; filter(); }));
        function reveal() {
          const target = document.getElementById(location.hash.slice(1));
          if (target && target.tagName === 'ARTICLE') { namespace = ''; search.value = ''; filter(); target.scrollIntoView(); }
        }
        addEventListener('hashchange', reveal); reveal();
    """.trimIndent()

