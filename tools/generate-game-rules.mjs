import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const catalog = JSON.parse(readFileSync(new URL('../src/main/resources/stdlib/game-rules.json', import.meta.url), 'utf8'));
const destination = new URL('../src/main/mcfpp/minecraft/GameRules.mcfpp', import.meta.url);
const lines = [
  '// Generated from src/main/resources/stdlib/game-rules.json by tools/generate-game-rules.mjs.',
  '/// 当前编译目标支持的类型化游戏规则。',
  'object data GameRules {'
];
for (const rule of catalog.rules) {
  lines.push(`#if MC >= ${rule.since}`);
  if (rule.until) lines.push(`#if MC < ${rule.until}`);
  lines.push(`    /// ${rule.id}，值类型为 ${rule.type}。`,
    `    var ${rule.name}: GameRule<${rule.type}> { get = top.mcfpp.mni.minecraft.GameRulesData }`);
  if (rule.until) lines.push('#endif');
  lines.push('#endif');
}
const source = [...lines, '}', ''].join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== source) {
    throw new Error(`Regenerate ${fileURLToPath(destination)} with node tools/generate-game-rules.mjs`);
  }
} else {
  writeFileSync(destination, source, 'utf8');
}

const provider = new URL('../src/main/kotlin/top/mcfpp/mni/minecraft/GameRulesData.kt', import.meta.url);
const names = [...new Set(catalog.rules.map(rule => rule.name))];
const kotlin = [
  'package top.mcfpp.mni.minecraft', '',
  'import top.mcfpp.annotations.MNIAccessor',
  'import top.mcfpp.mni.NativeCallContext', '',
  '/** Generated by tools/generate-game-rules.mjs. Getters return immutable rule descriptors. */',
  '@top.mcfpp.mni.annotation.NoExternalWrites',
  'object GameRulesData {',
  ...names.flatMap(name => [
    `    @JvmStatic @MNIAccessor("${name}")`,
    `    fun ${name}(context: NativeCallContext) = GameRuleData.constant(context, "${name}")`
  ]), '}', ''
].join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(provider, 'utf8').replaceAll('\r\n', '\n') !== kotlin) throw new Error('Regenerate GameRulesData.kt');
} else writeFileSync(provider, kotlin, 'utf8');
